def plot_confidence_ellipse(ax, x, y, n_std=2, facecolor='none', **kwargs):
    if len(x) < 3:
        return
    cov  = np.cov(x, y)
    vals, vecs = np.linalg.eigh(cov)
    order = vals.argsort()[::-1]
    vals, vecs = vals[order], vecs[:, order]
    theta  = np.degrees(np.arctan2(*vecs[:, 0][::-1]))
    width, height = 2 * n_std * np.sqrt(np.abs(vals))
    ellipse = Ellipse(
        xy=(np.mean(x), np.mean(y)),
        width=width, height=height,
        angle=theta,
        facecolor=facecolor, **kwargs
    )
    ax.add_patch(ellipse)

def run_permanova_euclidean(X, ids, groups_series):
    dist_mat = cdist(X, X, metric='euclidean')
    dm = DistanceMatrix(dist_mat, ids=ids)
    result = permanova(dm, groups_series, permutations=999)
    f_stat = result['test statistic']
    p_val = result['p-value']

    n_samples = result['sample size']
    n_groups = len(groups_series.unique())
    df_a = n_groups - 1
    df_w = n_samples - n_groups
    r2 = (f_stat * df_a) / (f_stat * df_a + df_w)

    return f_stat, r2, p_val

def draw_panel(ax, coords, groups_series, xlabel, ylabel, title):
    """Draw scatter + ellipses on a given Axes."""
    pc_df = pd.DataFrame(coords, columns=['D1', 'D2'])
    pc_df['group'] = groups_series.values

    sns.scatterplot(
        data=pc_df, x='D1', y='D2',
        hue='group', hue_order=HUE_ORDER, palette=COLORS,
        s=55, edgecolor='k', lw=0.4, alpha=0.85,
        ax=ax, legend=True
    )
    for grp in HUE_ORDER:
        if grp in pc_df['group'].unique():
            sub   = pc_df[pc_df['group'] == grp]
            color = COLORS[grp]
            plot_confidence_ellipse(
                ax, sub['D1'].values, sub['D2'].values,
                n_std=2, edgecolor=color, facecolor=color,
                alpha=0.15, lw=2
            )
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_title(title, fontweight='bold', fontsize=13)

    # Clean up legend
    handles, labels = ax.get_legend_handles_labels()
    ax.legend(handles, labels, title='Group',
              frameon=False, fontsize=10, title_fontsize=10)

