# 4.  SINGLE VIOLIN PANEL FUNCTION
# ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
def draw_violin(ax, df, col, label, kw_p, pw, show_ylabel=True, fontsize_title=11):
    """Draw one publication-quality violin+box+mean panel."""
    grp_pos = {g: i for i, g in enumerate(ORDER)}
    plot_df = df[[col,"Group"]].dropna()

    # ???? 1. Violin ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????
    parts = ax.violinplot(
        [plot_df.loc[plot_df.Group==g, col].values for g in ORDER],
        positions=range(len(ORDER)),
        widths=0.65, showmedians=False, showextrema=False
    )
    for body, grp in zip(parts["bodies"], ORDER):
        body.set_facecolor(LIGHT[grp])
        body.set_edgecolor(COLORS[grp])
        body.set_linewidth(1.2)
        body.set_alpha(0.85)

    # ???? 2. Boxplot (narrow, on top) ????????????????????????????????????????????????????????????????????????????????
    bp = ax.boxplot(
        [plot_df.loc[plot_df.Group==g, col].values for g in ORDER],
        positions=range(len(ORDER)),
        widths=0.12,
        patch_artist=True,
        showcaps=True,
        whiskerprops=dict(linewidth=1.0, color="dimgray"),
        capprops=dict(linewidth=1.0, color="dimgray"),
        medianprops=dict(linewidth=2.0),
        flierprops=dict(marker="o", markersize=2, alpha=0.4,
                        markeredgewidth=0.5),
        zorder=3,
    )
    for patch, grp in zip(bp["boxes"], ORDER):
        patch.set_facecolor("white")
        patch.set_edgecolor(COLORS[grp])
        patch.set_linewidth(1.2)
    for median, grp in zip(bp["medians"], ORDER):
        median.set_color(COLORS[grp])
    for flier, grp in zip(bp["fliers"], ORDER):
        flier.set_markerfacecolor(COLORS[grp])
        flier.set_markeredgecolor(COLORS[grp])

    # ???? 3. Mean ??marker ????????????????????????????????????????????????????????????????????????????????????????????????????
    for i, grp in enumerate(ORDER):
        vals = plot_df.loc[plot_df.Group==grp, col].dropna()
        if len(vals) == 0: continue
        mu   = vals.mean()
        ax.plot(i, mu, marker="D", color=COLORS[grp],
                markersize=5, zorder=5,
                markeredgecolor="white", markeredgewidth=0.8)

    # ???? 4. Strip (jittered raw points) ????????????????????????????????????????????????????????????????????????
    rng = np.random.default_rng(42)
    for i, grp in enumerate(ORDER):
        vals = plot_df.loc[plot_df.Group==grp, col].dropna().values
        if len(vals) == 0: continue
        jitter = rng.uniform(-0.08, 0.08, len(vals))
        ax.scatter(i + jitter, vals, s=5, color=COLORS[grp],
                   alpha=0.35, linewidths=0, zorder=2)

    # ???? 5. Significance bars ??????????????????????????????????????????????????????????????????????????????????????????????
    all_vals = plot_df[col].dropna()
    if len(all_vals) > 0:
        y_max    = all_vals.max()
        y_range  = all_vals.max() - all_vals.min()
        step     = y_range * 0.10

        sig_pairs = [(k, v) for k, v in pw.items() if v["sig"] != "ns"]
        sig_pairs.sort(key=lambda x: abs(grp_pos[x[0][0]] - grp_pos[x[0][1]]))

        used_levels = []
        for (g1, g2), info in sig_pairs:
            x1, x2 = grp_pos[g1], grp_pos[g2]
            h = y_max + step
            while any(abs(h - hl) < step * 0.75 for hl in used_levels):
                h += step
            used_levels.append(h)
            bar_h = step * 0.25
            ax.plot([x1, x1, x2, x2],
                    [h, h + bar_h, h + bar_h, h],
                    lw=0.9, color="black")
            ax.text((x1+x2)/2, h + bar_h + step*0.05,
                    info["sig"], ha="center", va="bottom",
                    fontsize=7.5, fontweight="bold")
                    
        # Auto-expand y-limit for bars
        if used_levels:
            top_bar = max(used_levels) + step * 0.6
            ax.set_ylim(top=max(ax.get_ylim()[1], top_bar))

    # ???? 6. Kruskal-Wallis annotation ??????????????????????????????????????????????????????????????????????????
    kw_txt = f"KW: {fmt_p(kw_p)}"
    ax.text(0.98, 0.99, kw_txt, transform=ax.transAxes,
            fontsize=6.5, ha="right", va="top", color="dimgray",
            style="italic")

    # ???? 7. Axes decoration ????????????????????????????????????????????????????????????????????????????????????????????????
    ax.set_xticks(range(len(ORDER)))
    ax.set_xticklabels(ORDER, fontsize=9, fontweight="bold")
    for tick, grp in zip(ax.get_xticklabels(), ORDER):
        tick.set_color(COLORS[grp])
    ax.tick_params(axis="y", labelsize=7.5)
    if show_ylabel:
        ax.set_ylabel("log$_2$(intensity + 1)", fontsize=8)
    ax.set_xlabel("")
    ax.set_title(label, fontsize=fontsize_title, fontweight="bold", pad=5)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_linewidth(0.7)
    ax.spines["bottom"].set_linewidth(0.7)


