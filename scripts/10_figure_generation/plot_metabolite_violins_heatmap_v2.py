# 3.  STATISTICS HELPERS
# ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
def run_stats(df, col, grp_col="Group", groups=ORDER):
    """
    Returns
    -------
    kw_p   : Kruskal-Wallis p
    pw     : dict {(g1,g2): {'p_raw', 'p_adj', 'sig'}}
    
    Note: Pairwise Mann??閘itney U tests are corrected within each metabolite 
          using Benjamini??油chberg FDR across the 3 pairwise comparisons.
    """
    arrays  = [df.loc[df[grp_col]==g, col].dropna().values for g in groups]
    if any(len(a) < 2 for a in arrays):
        pw = {(g1,g2): {"p_raw": np.nan, "p_adj": np.nan, "sig": "ns"} for g1,g2 in combinations(groups, 2)}
        return np.nan, pw
        
    _, kw_p = stats.kruskal(*arrays)

    pairs   = list(combinations(groups, 2))
    p_raws  = []
    for g1, g2 in pairs:
        a = df.loc[df[grp_col]==g1, col].dropna()
        b = df.loc[df[grp_col]==g2, col].dropna()
        _, p = stats.mannwhitneyu(a, b, alternative="two-sided")
        p_raws.append(p)

    _, p_adjs, _, _ = multipletests(p_raws, method="fdr_bh")
    pw = {}
    for (g1,g2), p_r, p_a in zip(pairs, p_raws, p_adjs):
        sig = "***" if p_a < 0.001 else ("**" if p_a < 0.01 else
              ("*"  if p_a < 0.05  else "ns"))
        pw[(g1,g2)] = {"p_raw": p_r, "p_adj": p_a, "sig": sig}
    return kw_p, pw


def fmt_p(p):
    if pd.isna(p): return "p=NA"
    if p < 0.0001: return "p<0.0001"
    return f"p={p:.4f}"

